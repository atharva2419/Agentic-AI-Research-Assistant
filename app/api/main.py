"""The FastAPI app: HTTP routes for the web UI and a live event stream (SSE).

FastAPI's job here is thin on purpose. It translates HTTP into calls on the SessionRunner and the
MemoryService and turns results into JSON. All research logic stays in the orchestrator, which the
CLI also uses.

Run it:  uv run uvicorn app.api.main:app --reload --port 8000
API docs (generated by FastAPI from the type hints):  http://localhost:8000/docs
"""

