"""The FastAPI app: HTTP routes for the web UI and a live event stream (SSE).

FastAPI's job here is thin on purpose. It translates HTTP into calls on the SessionRunner and
turns results into JSON. All research logic stays in the orchestrator, which the CLI also uses.

Run it:  uv run uvicorn app.api.main:app --reload --port 8000
API docs (generated by FastAPI from the type hints):  http://localhost:8000/docs
"""

import asyncio
from collections.abc import AsyncIterator
from contextlib import asynccontextmanager
from pathlib import Path
from typing import Annotated, Any

from fastapi import APIRouter, Body, Depends, FastAPI, HTTPException, Request, status
from fastapi.responses import PlainTextResponse, StreamingResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, Field

from app.api.events import KEEPALIVE, ServerEvent, format_sse, session_view
from app.api.runner import SessionNotFound, SessionRunner
from app.api.store import InMemorySessionStore
from app.config import PROJECT_ROOT, get_settings
from app.models import Mode, ResearchSession, SessionSettings, UserCommand
from app.orchestrator.errors import CommandRejected
from app.orchestrator.orchestrator import Orchestrator
from app.report_render import report_to_markdown
from app.wiring import Wiring, build_wiring

UI_DIST = PROJECT_ROOT / "ui" / "dist"
KEEPALIVE_SECONDS = 15.0


class CreateSession(BaseModel):
    topic: str = Field(min_length=3, max_length=300)
    mode: Mode = Mode.SUPERVISED
    recency_days: int = Field(default=365, ge=1, le=3650)
    user_id: str = Field(default="demo", min_length=1, max_length=64)


class SessionSummary(BaseModel):
    id: str
    topic: str
    status: str
    mode: str
    created_at: str
    cost_usd: float


router = APIRouter(prefix="/api")


def get_runner(request: Request) -> SessionRunner:
    runner: SessionRunner = request.app.state.runner
    return runner


def get_wiring(request: Request) -> Wiring:
    wiring: Wiring = request.app.state.wiring
    return wiring


Runner = Annotated[SessionRunner, Depends(get_runner)]


def _session_or_404(runner: SessionRunner, session_id: str) -> ResearchSession:
    try:
        return runner.get(session_id).session
    except SessionNotFound:
        raise HTTPException(status.HTTP_404_NOT_FOUND, f"no session {session_id}") from None


@router.get("/health")
def health(wiring: Annotated[Wiring, Depends(get_wiring)]) -> dict[str, Any]:
    return {"status": "ok", "offline": wiring.offline}


@router.get("/blueprint")
def blueprint(wiring: Annotated[Wiring, Depends(get_wiring)]) -> dict[str, Any]:
    return wiring.deps.blueprint.model_dump(mode="json")


@router.post("/sessions", status_code=status.HTTP_201_CREATED)
async def create_session(body: CreateSession, runner: Runner) -> dict[str, Any]:
    # Must be `async def`: FastAPI runs plain `def` routes in a worker thread, where there is no
    # event loop to start the session's background task on.
    threshold = runner.orchestrator.deps.blueprint.filtering.relevance_threshold
    session = ResearchSession(
        user_id=body.user_id,
        topic=body.topic.strip(),
        mode=body.mode,
        settings=SessionSettings(recency_days=body.recency_days, relevance_threshold=threshold),
    )
    runner.start(session)
    return session_view(session)


@router.get("/sessions")
def list_sessions(runner: Runner, user_id: str | None = None) -> list[SessionSummary]:
    return [
        SessionSummary(
            id=s.id,
            topic=s.topic,
            status=s.status.value,
            mode=s.mode.value,
            created_at=s.created_at.isoformat(),
            cost_usd=round(s.budget.cost_usd, 4),
        )
        for s in runner.store.list_sessions(user_id)
    ]


@router.get("/sessions/{session_id}")
def get_session(session_id: str, runner: Runner) -> dict[str, Any]:
    return session_view(_session_or_404(runner, session_id))


@router.post("/sessions/{session_id}/commands")
async def post_command(
    session_id: str, command: Annotated[UserCommand, Body()], runner: Runner
) -> dict[str, Any]:
    """Every human action goes through here: answer, approve, pause, resume (more in Phase 6).
    The body's `type` field picks the command; Pydantic rejects unknown types with HTTP 422."""
    _session_or_404(runner, session_id)
    try:
        session = await runner.submit(session_id, command)
    except CommandRejected as exc:
        raise HTTPException(status.HTTP_409_CONFLICT, str(exc)) from None
    return session_view(session)


@router.get("/sessions/{session_id}/report.md", response_class=PlainTextResponse)
def report_markdown(session_id: str, runner: Runner) -> PlainTextResponse:
    session = _session_or_404(runner, session_id)
    return PlainTextResponse(
        report_to_markdown(session),
        media_type="text/markdown",
        headers={"Content-Disposition": f'attachment; filename="report-{session_id}.md"'},
    )


@router.get("/sessions/{session_id}/events")
async def session_events(session_id: str, request: Request, runner: Runner) -> StreamingResponse:
    """Server-Sent Events: a snapshot first, then live `log` and `snapshot` events."""
    _session_or_404(runner, session_id)
    handle = runner.get(session_id)

    async def stream() -> AsyncIterator[str]:
        # Subscribe before taking the snapshot, so no event can slip in between.
        async with handle.bus.subscribe() as queue:
            yield format_sse(ServerEvent(type="snapshot", data=session_view(handle.session)))
            while not await request.is_disconnected():
                try:
                    event = await asyncio.wait_for(queue.get(), timeout=KEEPALIVE_SECONDS)
                except TimeoutError:
                    yield KEEPALIVE
                    continue
                yield format_sse(event)

    return StreamingResponse(
        stream(),
        media_type="text/event-stream",
        headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"},
    )


def create_app(wiring: Wiring | None = None, export_dir: Path | None = None) -> FastAPI:
    """Build the app. Tests pass their own wiring (fakes); production builds it from settings.
    `export_dir`: where finished sessions are written (None = nowhere, as in most tests)."""

    @asynccontextmanager
    async def lifespan(app: FastAPI) -> AsyncIterator[None]:
        active = wiring or build_wiring(get_settings())
        app.state.wiring = active
        app.state.runner = SessionRunner(
            Orchestrator(active.deps), InMemorySessionStore(), export_dir=export_dir
        )
        yield
        await app.state.runner.shutdown()
        await active.close()

    app = FastAPI(
        title="Research Assistant API",
        description="Agentic research assistant: plans, searches, filters, summarizes, cites.",
        lifespan=lifespan,
    )
    app.include_router(router)
    if UI_DIST.is_dir():
        # After `npm run build`, the API also serves the UI: one URL for the demo and Docker.
        app.mount("/", StaticFiles(directory=UI_DIST, html=True), name="ui")
    return app


app = create_app(export_dir=get_settings().data_dir)
